import { afterEach, describe, expect, test } from "bun:test";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { AcpAgentClient, assertPathInsideWorkspace } from "@codeteams/acp";
import { CodeTeamsStorage, projectsTable } from "@codeteams/storage";
import { eq } from "drizzle-orm";

const mockServerPath = resolve(
  import.meta.dir,
  "../fixtures/mock-acp-server.ts"
);

const tempDirs: string[] = [];

function createTempDir(prefix: string): string {
  const dir = mkdtempSync(join(tmpdir(), prefix));
  tempDirs.push(dir);
  return dir;
}

afterEach(() => {
  while (tempDirs.length > 0) {
    const dir = tempDirs.pop()!;
    try {
      rmSync(dir, { recursive: true, force: true });
    } catch {
      // Ignore cleanup race on Windows
    }
  }
});

describe("M0: Bun + ACP SDK v1 real stdio bidirectional communication", () => {
  test("initialize, newSession, streaming prompt, and fs callbacks over stdio", async () => {
    const workspace = createTempDir("codeteams-ws-");
    writeFileSync(join(workspace, "hello.txt"), "Hello CodeTeams", "utf8");

    const updates: string[] = [];
    const fileEvents: Array<{ op: string; allowed: boolean }> = [];

    const client = new AcpAgentClient({
      command: process.execPath,
      args: ["run", mockServerPath],
      cwd: workspace,
      env: {
        MOCK_AGENT_NAME: "m0-test-agent",
        MOCK_READ_FILE: "hello.txt",
        MOCK_WRITE_FILE: "out/result.txt",
        MOCK_DELAY_MS: "5",
      },
      callbacks: {
        onSessionUpdate(notification) {
          if (notification.update.sessionUpdate === "agent_message_chunk") {
            if (notification.update.content.type === "text") {
              updates.push(notification.update.content.text);
            }
          }
        },
        onFileAccess(entry) {
          fileEvents.push({ op: entry.op, allowed: entry.allowed });
        },
      },
    });

    try {
      const init = await client.connect();
      expect(init.protocolVersion).toBe(1);
      expect(init.agentInfo?.name).toBe("m0-test-agent");

      const sess = await client.newSession(workspace);
      expect(sess.sessionId).toMatch(/^mock_sess_/);

      const promptRes = await client.prompt(sess.sessionId, [
        { type: "text", text: "Verify M0 bidirectional ACP stdio" },
      ]);
      expect(promptRes.stopReason).toBe("end_turn");

      const combined = updates.join("");
      expect(combined).toContain("[read:hello.txt:15chars]");
      expect(combined).toContain("[m0-test-agent] Completed step");

      const written = readFileSync(join(workspace, "out", "result.txt"), "utf8");
      expect(written).toContain("Generated by m0-test-agent");
      expect(fileEvents.some((e) => e.op === "read" && e.allowed)).toBe(true);
      expect(fileEvents.some((e) => e.op === "write" && e.allowed)).toBe(true);
    } finally {
      await client.close();
    }
  });

  test("permission rejection stops turn with refusal and does not auto-approve", async () => {
    const workspace = createTempDir("codeteams-perm-");
    let sawPermissionRequest = false;

    const client = new AcpAgentClient({
      command: process.execPath,
      args: ["run", mockServerPath],
      cwd: workspace,
      env: {
        MOCK_AGENT_NAME: "perm-agent",
        MOCK_REQUEST_PERMISSION: "1",
        MOCK_DELAY_MS: "0",
      },
      callbacks: {
        async onPermissionRequest(req) {
          sawPermissionRequest = true;
          const reject = req.options.find((o) => o.kind === "reject_once");
          return {
            outcome: {
              outcome: "selected",
              optionId: reject!.optionId,
            },
          };
        },
      },
    });

    try {
      await client.connect();
      const sess = await client.newSession(workspace);
      const res = await client.prompt(sess.sessionId, [
        { type: "text", text: "Attempt gated edit" },
      ]);
      expect(sawPermissionRequest).toBe(true);
      expect(res.stopReason).toBe("refusal");
    } finally {
      await client.close();
    }
  });

  test("path guard rejects directory traversal outside workspace", () => {
    const workspace = createTempDir("codeteams-guard-");
    expect(() =>
      assertPathInsideWorkspace(workspace, "../outside-secret.txt")
    ).toThrow(/escapes authorized workspace/i);
  });

  test("loadSession replays history when agent advertises loadSession", async () => {
    const workspace = createTempDir("codeteams-load-");
    const stateFile = join(workspace, ".mock-sessions.json");

    // First process creates session and completes a turn
    const client1 = new AcpAgentClient({
      command: process.execPath,
      args: ["run", mockServerPath],
      cwd: workspace,
      env: {
        MOCK_AGENT_NAME: "resumable-agent",
        MOCK_SUPPORTS_LOAD: "1",
        MOCK_STATE_FILE: stateFile,
        MOCK_DELAY_MS: "0",
      },
    });

    let sessionId: string;
    try {
      await client1.connect();
      expect(client1.supportsLoadSession).toBe(true);
      const s = await client1.newSession(workspace);
      sessionId = s.sessionId;
      await client1.prompt(sessionId, [
        { type: "text", text: "Remember alpha-123" },
      ]);
    } finally {
      await client1.close();
    }

    // Second process loads same session and receives replay chunks
    const replayed: string[] = [];
    const client2 = new AcpAgentClient({
      command: process.execPath,
      args: ["run", mockServerPath],
      cwd: workspace,
      env: {
        MOCK_AGENT_NAME: "resumable-agent",
        MOCK_SUPPORTS_LOAD: "1",
        MOCK_STATE_FILE: stateFile,
        MOCK_DELAY_MS: "0",
      },
      callbacks: {
        onSessionUpdate(n) {
          if (
            (n.update.sessionUpdate === "user_message_chunk" ||
              n.update.sessionUpdate === "agent_message_chunk") &&
            n.update.content.type === "text"
          ) {
            replayed.push(n.update.content.text);
          }
        },
      },
    });

    try {
      await client2.connect();
      await client2.loadSession(sessionId, workspace);
      await client2.flushUpdates();
      expect(replayed.join(" ")).toContain("Remember alpha-123");
    } finally {
      await client2.close();
    }
  });
});

describe("M0: bun:sqlite + Drizzle migrations, persistence, and online backup", () => {
  test("initializes WAL SQLite, persists across restart, and creates safe backup", () => {
    const userData = createTempDir("codeteams-db-");
    const storage1 = new CodeTeamsStorage(userData);
    const diag = storage1.getDiagnostics();

    expect(diag.journalMode.toLowerCase()).toBe("wal");
    expect(diag.foreignKeys).toBe(1);
    expect(diag.schemaVersions).toContain(1);

    const now = new Date().toISOString();
    storage1.db
      .insert(projectsTable)
      .values({
        id: "proj-1",
        name: "Demo Repo",
        canonicalPath: userData,
        gitRoot: null,
        createdAt: now,
        lastOpenedAt: now,
        archivedAt: null,
      })
      .run();

    const artifact = storage1.writeArtifactFile(
      "proj-1",
      "run-1",
      "plan.md",
      "# Implementation Plan\n"
    );
    expect(artifact.size).toBeGreaterThan(0);
    expect(artifact.contentHash).toHaveLength(64);

    const backup = storage1.createBackup("m0");
    expect(readFileSync(backup.backupPath).byteLength).toBeGreaterThan(0);
    storage1.close();

    // Reopen fresh storage instance and confirm persistence
    const storage2 = new CodeTeamsStorage(userData);
    const found = storage2.db
      .select()
      .from(projectsTable)
      .where(eq(projectsTable.id, "proj-1"))
      .get();
    expect(found?.name).toBe("Demo Repo");
    storage2.close();
  });
});
